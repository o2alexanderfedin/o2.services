/**
 * The names of the requirements the two files do not satisfy, in declaration order.
 *
 * A plain function over content, separated from the reads above so the planted cases can
 * prove it reports something. A scan that reports nothing against the real files proves
 * nothing until it has been watched reporting something.
 */
function unmetRequirements(report: string, frozen: string): string[] {
  return REQUIREMENTS.filter(({ satisfiedBy }) => !satisfiedBy(report, frozen)).map(({ name }) => name)
}

function describeUnmet(names: readonly string[]): string[] {
  return names.map((name) => {
    const reason = REQUIREMENTS.find((requirement) => requirement.name === name)?.reason ?? ''
    return `${REPORT_PATH} — missing: ${name}. Why it matters: ${reason}`
  })
}

