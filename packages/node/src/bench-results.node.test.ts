/**
 * The published report, held to its own provenance — BENCH-07 criterion 4.
 *
 * **What this is.** A guard over a *published artifact*, in the idiom
 * `bench-egress.node.test.ts` uses for a source file: a requirement array with a name, a
 * check, a reason and a fragment that satisfies it; a plain function over strings; planted
 * inputs that prove the matcher can report one requirement at a time; and anti-vacuity
 * assertions that prove it read anything at all.
 *
 * **What this is not.** It cannot tell whether a number is right. It reads
 * `.planning/BENCHMARK-RESULTS.md`, not the driver, so every figure in it is opaque here.
 * What it can tell is whether the file that carries those figures says where each one came
 * from, and whether it still carries the ones it used to.
 *
 * **Why that is worth a test at all.** A driver that renders provenance correctly and a
 * report file that lost half its rungs to a partial commit are indistinguishable from
 * inside the driver — the driver renders what it was handed and exits. The file is what a
 * reader meets, and nothing else in this repository reads it. `bin/bench.ts` runs `main()`
 * on import and no npm script invokes it, so the artifact is not regenerated by any suite:
 * between one hand-run benchmark and the next, this file is the only thing standing between
 * the published report and a silent edit.
 *
 * **The second block is not about the artifact at all.** See its own comment: an artifact
 * guard cannot see the driver, so a deleted renderer leaves the committed report
 * byte-identical and every requirement below green.
 */

