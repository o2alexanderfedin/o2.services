// ── the section scan ──────────────────────────────────────────────────────────────────

interface Section {
  /** The `## ` line, without its marker. */
  readonly heading: string
  /** Everything under it up to the next `## `. */
  readonly body: string
}

/**
 * Split a report into its `## ` sections.
 *
 * **The first piece is dropped, and that is load-bearing.** It is the `# ` title block,
 * whose bolded same-machine line carries a node count — digits inside a bolded run — so a
 * scan that kept it would hold a preamble belonging to no section to a rule about section
 * headings.
 */
function sectionsOf(report: string): Section[] {
  const [, ...rest] = report.split(/^## /m)
  return rest.map((piece) => {
    const newline = piece.indexOf('\n')
    return newline === -1
      ? { heading: piece.trim(), body: '' }
      : { heading: piece.slice(0, newline).trim(), body: piece.slice(newline + 1) }
  })
}

/**
 * Whether a section states a number.
 *
 * Three forms, because this report states its figures in three different ways and a scan
 * missing any one of them silently exempts whichever sections use it.
 */
const FIGURE_FORMS: readonly RegExp[] = [
  /** Any Markdown table row: makespan, reduce, tax, inventory, exclusions, processes. */
  /^\|/m,
  /** A bolded run containing a digit: `## Supplementary`, whose figures are bolded prose. */
  /\*\*[^*\n]*\d[^*\n]*\*\*/,
  /**
   * A decimal carrying a unit, anywhere. **This is the form an earlier draft of the plan
   * was missing**, and it is why that draft did not guard the largest number in the file:
   * `7086.14×` sits in plain prose, `## COST crossover` has no table row at all, and its
   * only bolded text is `**No crossover.**`, which carries no digit.
   */
  /\d+\.\d+\s*(?:×|ms|%)/,
]

const carriesAFigure = (body: string): boolean => FIGURE_FORMS.some((form) => form.test(body))

/**
 * A driver named in the heading itself.
 *
 * `\b(?:in-process|process-per-node)\b` and deliberately not a looser pattern such as
 * `/process/`: every makespan heading interpolates a same-machine label containing the word
 * `nodes`, and a run whose label said `processes` would satisfy a looser pattern — which is
 * how this check would pass vacuously on exactly the headings it exists to hold.
 *
 * The heading and not the body, because criterion 4 is about a reader meeting a number and
 * seeing where it came from without reading the surrounding prose.
 */
const NAMES_A_DRIVER = /\b(?:in-process|process-per-node)\b/

interface Exemption {
  /** Matched against the heading text, so it holds however the section's prose is worded. */
  readonly heading: string
  readonly reason: string
}

/**
 * The only two sections excused from naming a driver.
 *
 * **The polarity is the point.** An unrecognised section is guarded by default and only
 * these two are excused, so a section added later is held to the rule without anybody
 * remembering to add it.
 */
const EXEMPT_SECTIONS: readonly Exemption[] = [
  {
    heading: 'What these numbers do NOT establish',
    reason:
      'a driver name in the heading of the section that says what the run does *not* show would ' +
      'be meaningless — the section is about the absence of measurements, and every entry in it ' +
      'names its own scope in its own words',
  },
  {
    heading: 'Machine inventory',
    reason:
      'host facts rather than measurements: the CPU model, the core count and the runtime version ' +
      'are the same whichever driver produced the curves beneath',
  },
]

const exemptionFor = (heading: string): Exemption | undefined =>
  EXEMPT_SECTIONS.find((entry) => heading.startsWith(entry.heading))

/** Sections carrying a figure that are not exempt — the population requirement 2 holds. */
function heldSections(report: string): Section[] {
  return sectionsOf(report).filter(
    (section) => exemptionFor(section.heading) === undefined && carriesAFigure(section.body),
  )
}

