describe('the published benchmark report says where every figure came from', () => {
  it('reads the two real files rather than an empty string', () => {
    // Anti-vacuity. `readFileSync` would have thrown on a wrong path, but a truncated or
    // replaced file would not — and every negative check below is satisfied by an empty
    // string. This is the reading the whole file rests on, and it runs over **both**
    // artifacts, because the frozen one is the only place the preserved values live.
    expect(REPORT.length).toBeGreaterThan(2_000)
    expect(REPORT).toContain('# o2.services — benchmark run')
    expect(REPORT).toContain('## Machine inventory')

    expect(FROZEN.length).toBeGreaterThan(2_000)
    expect(FROZEN).toContain('# o2.services — benchmark run')
    expect(FROZEN).toContain('## Machine inventory')
  })

  it('finds at least eight figure-carrying sections that are not exempt', () => {
    // The scan is proved able to see a section at all. Against the file as committed
    // before this phase measured anything the count is exactly eight — the two makespan
    // tables, the two reduce trees, the exclusions, the connectivity tax, the COST
    // crossover and the supplementary decomposition. A floor rather than an equality, so a
    // report that legitimately grows a section does not turn this red; the post-run file
    // has more. Without this reading, a broken splitter would report zero held sections
    // and requirement 2 would pass by finding nothing to hold.
    expect(heldSections(REPORT).length).toBeGreaterThanOrEqual(8)
  })

  it('registers no exemption that matches nothing in the report', () => {
    // A dead exemption is worse than no exemption: it silently excuses a section that no
    // longer exists, and the next section to take that name inherits the excuse.
    const dead = EXEMPT_SECTIONS.filter(
      (entry) => !sectionsOf(REPORT).some((section) => section.heading.startsWith(entry.heading)),
    ).map((entry) => entry.heading)
    expect(dead).toEqual([])
  })

  it('satisfies every provenance requirement', () => {
    expect(describeUnmet(unmetRequirements(REPORT, FROZEN))).toEqual([])
  })
})

describe('the scan can report one unmet requirement at a time — proved by planting', () => {
  it('reports nothing against a report and an artifact that satisfy all of them', () => {
    // The control, and it is what makes the three plants below mean anything: a fixture
    // that failed a requirement for its own reasons would report the same name a plant
    // does, and the planted case would pass while measuring the fixture rather than the
    // plant.
    expect(unmetRequirements(SATISFYING_REPORT, SATISFYING_FROZEN)).toEqual([])
  })

  it('reports only the frozen-values requirement when a preserved figure is deleted', () => {
    // A Markdown report has no comments, so there is no comments-only control to plant.
    // This is its replacement: the largest number the 2026-08-01 run published, removed
    // from the file that exists to preserve it. A row-shape pattern would not catch this,
    // which is why requirement 3 asserts values.
    const withoutTheCrossover = SATISFYING_FROZEN.split('\n')
      .filter((line) => !line.includes('7086.14×'))
      .join('\n')
    const unmet = unmetRequirements(SATISFYING_REPORT, withoutTheCrossover)
    expect(unmet.length).toBeGreaterThan(0)
    expect(unmet).toEqual([REQUIREMENTS[2]?.name])
  })

  it('reports only the section-scan requirement when a table-bearing section names no driver', () => {
    const withALatencySection = `${SATISFYING_REPORT}\n## Latency\n\n| nodes | p50 |\n|---|---|\n| 8 | 12.5ms |\n`
    const unmet = unmetRequirements(withALatencySection, SATISFYING_FROZEN)
    expect(unmet.length).toBeGreaterThan(0)
    expect(unmet).toEqual([REQUIREMENTS[1]?.name])
  })

  it('reports only the section-scan requirement when a section’s only figure is a decimal in prose', () => {
    // The mutation an earlier draft of this guard could not have caught: no table row, no
    // bolded digit, one decimal carrying a unit in plain prose. It is the shape
    // `## COST crossover` has, and that section carries the largest number in the report.
    const withProseOnly = `${SATISFYING_REPORT}\n## Overhead\n\nMeasured against the control, a factor of 91.4×.\n`
    const unmet = unmetRequirements(withProseOnly, SATISFYING_FROZEN)
    expect(unmet.length).toBeGreaterThan(0)
    expect(unmet).toEqual([REQUIREMENTS[1]?.name])
  })
})

// ── the source-linkage block ──────────────────────────────────────────────────────────

/**
 * **The defect this block closes: an artifact guard cannot see the driver.**
 *
 * Delete `processFabric(`, the integrity gate and the `## Processes` renderer from
 * `bin/bench.ts` and the committed report stays byte-identical, every requirement above
 * stays green, and the published pid table becomes a fossil — a record of a mechanism that
 * no longer exists, indistinguishable from a record of one that does. Nothing re-derives
 * it: `main()` runs on import so no suite can import the driver, and no npm script runs it.
 *
 * So every heading the block above demands of the artifact is required here to exist as a
 * literal in the code that generates it. Deleting a renderer is then a red test rather than
 * a stale artifact that still passes.
 *
 * **What linkage still cannot do.** It makes a *deleted* renderer red. It cannot make a
 * *broken* one red — a renderer that keeps its heading literal and emits wrong numbers
 * underneath satisfies every check in this file. That gap is real and is stated rather than
 * papered over; closing it needs a run, and the run is a hand-run benchmark.
 */
describe('every heading the published report is held to exists in the code that generates it', () => {
  /**
   * Interpolated headings are matched on their literal prefix — the part before the first
   * `${` — because the driver builds them from values read off the curve being rendered.
   */
  const DEMANDED: readonly string[] = [
    '## Makespan — memory transport, ',
    '## Makespan — real transport, ',
    '## Reduce tree — memory transport (',
    '## Reduce tree — real transport (',
    '## Configurations excluded, and why — ',
    '## Connectivity tax — ',
    '## COST crossover — ',
    '## Supplementary — where the time goes',
    '## Processes — process-per-node driver, saturating fixture',
    '## Speedup — in-process and process-per-node drivers, fixed redundancy 1, saturating fixture',
    '## The excluded rungs, re-measured — in-process and process-per-node drivers, trivial fixture',
    '## Earlier run — frozen (in-process driver, trivial fixture)',
    // Not a heading. A claim about *how* a published number was measured, so it must be a
    // literal beside the mechanism rather than a sentence a report inherited from an
    // earlier run — the same reason requirement 6 demands it in the artifact.
    'one call in flight at a time',
    // The three sentences requirements 3 and 8 hold the artifact to, required here for the
    // same reason: a report can only carry them if something writes them.
    'BENCHMARK-RESULTS-2026-08-01.md',
    'cannot detect divergence between machines',
    'unmeasured is not met',
  ]

  // Stripped, for the reason `bench-egress.node.test.ts` strips: `bin/bench.ts` names its
  // own renderers in its own prose, so a raw-text match would be satisfied by a comment
  // describing a renderer that had been deleted.
  const SOURCES = `${stripComments(BENCH_SOURCE)}\n${stripComments(REPORT_SOURCE)}`

  it('reads both generating sources rather than an empty string', () => {
    expect(stripComments(BENCH_SOURCE).length).toBeGreaterThan(5_000)
    expect(BENCH_SOURCE).toContain('async function realFabric')
    expect(stripComments(REPORT_SOURCE).length).toBeGreaterThan(2_000)
    expect(REPORT_SOURCE).toContain('export function renderMarkdown')
  })

  it('finds every demanded heading as a literal in bin/bench.ts or bench/src/report.ts', () => {
    const absent = DEMANDED.filter((heading) => !SOURCES.includes(heading))
    expect(absent).toEqual([])
  })
})
